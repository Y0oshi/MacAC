    public static readonly IReadOnlyDictionary<(uint InputMapId, uint ActionId), FeedAct> Map = Forward();

    public static readonly IReadOnlyDictionary<FeedAct, (uint InputMapId, uint ActionId)> ReverseLookup =
        Map.ToDictionary(static duo => duo.Value, static duo => duo.Key);

    public static bool TryResolve(uint feedLookupIdent, uint actIdent, out FeedAct act) => Map.TryGetValue((feedLookupIdent, actIdent), out act);

    public static bool TryFetchCanonPersona(FeedAct act, out (uint InputMapId, uint ActionId) persona) => ReverseLookup.TryGetValue(act, out persona);

    public static InputLayer AmbitForFeedLookup(uint feedLookupIdent)
    {
        return feedLookupIdent switch
        {
            0x00000006u => InputLayer.Camera,
            0x10000003u => InputLayer.MeleeCombat,
            0x10000004u => InputLayer.MissileCombat,
            0x10000005u => InputLayer.MagicCombat,
            _ => InputLayer.Game,
        };
    }

    public static ActivationKind ActivationFor(uint feedLookupIdent, uint actIdent)
    {
        bool pinned = (inputMapId: feedLookupIdent, actionId: actIdent) switch
        {
            (0x4u, 0x32u) => true,
            (0x5u or 0x6u, >= 0x33u and <= 0x38u) => true,
            (0x5u, 0x3Du or 0x3Eu) => true,
            (0x10000003u, >= 0x1000005Du and <= 0x1000005Fu) => true,
            (0x10000004u, >= 0x100000F1u and <= 0x100000F3u) => true,
            _ => false,
        };
        return pinned ? ActivationKind.Hold : ActivationKind.Press;
    }

    public static bool TryFetchToonKnobIdent(FeedAct act, out uint knobIdent)
    {
        knobIdent = 0u;
        if (!TryFetchCanonPersona(act, out (uint InputMapId, uint ActionId) persona) || persona.InputMapId != 0x10000008u)
            return false;

        knobIdent = persona.ActionId switch
        {
            // Three contiguous runs share one offset from the first option action.
            >= 0x10000071u and <= 0x10000074u => persona.ActionId - 0x10000071u,
            >= 0x10000076u and <= 0x10000083u => persona.ActionId - 0x10000071u,
            >= 0x10000085u and <= 0x10000093u => persona.ActionId - 0x10000071u,
            0x1000010Eu => 0x23u,
            0x1000010Fu => 0x24u,
            0x10000110u => 0x25u,
            0x10000112u => 0x26u,
            0x1000011Bu => 0x28u,
            0x1000011Du => 0x29u,
            0x1000011Eu => 0x2Au,
            0x1000011Fu => 0x2Bu,
            0x10000120u => 0x2Cu,
            0x10000123u => 0x2Du,
            0x10000125u => 0x2Eu,
            0x1000012Au => 0x2Fu,
            0x1000012Cu => 0x30u,
            0x1000012Fu => 0x32u,
            0x1000013Eu => 0x13u,
            _ => uint.MaxValue,
        };
        return knobIdent != uint.MaxValue;
    }

    private static Dictionary<(uint, uint), FeedAct> Forward()
    {
        var lookup = new Dictionary<(uint, uint), FeedAct>(Ranks.Length + Emotes.Length);
        foreach ((uint feedLookup, uint act, FeedAct modelled) in Ranks)
        {
            lookup[(feedLookup, act)] = modelled;
            // The emote block sits between the magic-combat and selection maps.
            if (feedLookup == 0x10000005u && act == 0x10000105u)
            {
                for (int idx = 0; idx < Emotes.Length; ++idx)
                    lookup[(EmoteLookupIdent, LeadEmoteActIdent + (uint)idx)] = Emotes[idx];
            }
        }
        return lookup;
    }
